/**
 * Writes js/config.js from environment variables (Netlify build or local CI).
 *
 * Required:
 *   WELINK_SUPABASE_URL
 *   WELINK_SUPABASE_ANON_KEY  (Supabase anon / publishable key)
 */
const fs = require("fs");
const path = require("path");

const url = (process.env.WELINK_SUPABASE_URL || "").trim();
const key = (process.env.WELINK_SUPABASE_ANON_KEY || "").trim();
const outPath = path.join(__dirname, "..", "js", "config.js");

if (!url || !key) {
  console.error(
    "[WeLink] Missing WELINK_SUPABASE_URL or WELINK_SUPABASE_ANON_KEY.\n" +
      "  Netlify: Site settings → Environment variables.\n" +
      "  Local: copy js/config.example.js → js/config.js"
  );
  process.exit(1);
}

const body = `/** Generated by scripts/generate-config.js - do not commit. */
window.WeLinkConfig = {
  SUPABASE_URL: ${JSON.stringify(url)},
  SUPABASE_KEY: ${JSON.stringify(key)}
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body, "utf8");
console.log("[WeLink] Wrote js/config.js");
